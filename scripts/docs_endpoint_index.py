def composed_routes():
    """Return sorted ``(method, path, module_key)`` for the API role."""
    import inspect
    from pathlib import Path

    from teamEvolver.app import create_app
    from teamEvolver.config import TeamEvolverConfig

    extras = {
        "config": TeamEvolverConfig(),
        "config_repo": object(),
        "session_payloads": object(),
        "console_sessions": object(),
    }
    services = SimpleNamespace(
        extras=extras,
        tx=SimpleNamespace(pool=SimpleNamespace(schema="te")),
        tasks=object(),
        leases=object(),
        role="api",
    )
    app = create_app(services=services)
    root = Path(__file__).resolve().parents[1]

    def walk(routes):
        for route in routes:
            nested = getattr(route, "original_router", None)
            if nested:
                yield from walk(nested.routes)
                continue
            endpoint = getattr(route, "endpoint", None)
            path = getattr(route, "path", None)
            if path is None or endpoint is None:
                continue
            source = Path(inspect.getsourcefile(endpoint)).resolve()
            rel = source.relative_to(root).as_posix() if root in source.parents else ""
            if not rel or rel.startswith(".venv/") or "site-packages" in rel:
                continue  # FastAPI's own /docs, /openapi.json
            module = next((key for key in MODULES if rel.startswith(key + "/")), None)
            if module is None:
                raise RuntimeError(f"route {path} from {rel} has no docs module")
            for method in getattr(route, "methods", None) or ():
                yield method, path, module

    return sorted(set(walk(app.routes)), key=lambda r: (list(MODULES).index(r[2]), r[1], r[0]))


def render(lang: str) -> str:
    rows = composed_routes()
    out = [HEADER[lang]]
    for module, (zh, en, page) in MODULES.items():
        items = [r for r in rows if r[2] == module]
        if not items:
            continue
        title = zh if lang == "zh" else en
        label = "详细说明" if lang == "zh" else "Details"
        out.append(f"\n## {title}\n\n{label}：[{page.split('/')[-1]}](../{page})\n\n| Method | Path |\n| --- | --- |")
        out.extend(f"| {method} | `{path}` |" for method, path, _ in items)
    total = "共" if lang == "zh" else "Total:"
    out.append(f"\n{total} {len(rows)}\n")
    return "\n".join(out)


if __name__ == "__main__":
    lang = sys.argv[1] if len(sys.argv) > 1 else "zh"
    if lang not in HEADER:
        raise SystemExit("usage: docs_endpoint_index.py zh|en")
    sys.stdout.write(render(lang))
